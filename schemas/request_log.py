from pydantic import BaseModel, Field
from datetime import datetime, date # Import date for summary filters
from typing import Optional, List # For list responses in summary
from decimal import Decimal # For estimated_cost

class RequestLogBase(BaseModel):
    request_id: str = Field(..., description="Unique ID for the request, typically a UUID generated by the SDK.")
    
    # Foreign key fields are now strings as per the updated RequestLog model
    api_key_id: str
    business_unit_id: str
    platform_id: str
    
    model_name: Optional[str] = None
    request_timestamp: datetime
    response_timestamp: datetime
    
    is_success: bool
    http_status_code: Optional[int] = None
    
    prompt_tokens: Optional[int] = None
    completion_tokens: Optional[int] = None
    total_tokens: Optional[int] = None
    # estimated_cost will be calculated server-side, so it's optional in create/base
    estimated_cost: Optional[Decimal] = Field(None, description="Estimated cost of the request, calculated server-side.") 
    
    error_message: Optional[str] = None
    user_ip_address: Optional[str] = None
    
    request_payload_preview: Optional[str] = None
    response_payload_preview: Optional[str] = None

class RequestLogCreate(RequestLogBase):
    # All fields from RequestLogBase are expected for creation,
    # except log_id which is auto-generated by the DB, and estimated_cost which is server-calculated.
    pass

class RequestLogRead(RequestLogBase):
    log_id: int # Include log_id for reading
    # estimated_cost should be present when reading a log after it's processed
    estimated_cost: Optional[Decimal] = Field(None, description="Estimated cost of the request.")

    class Config:
        orm_mode = True


# Schemas for Log Summary
class LogSummaryItem(BaseModel):
    group_by_value: str # e.g., the specific business_unit_id or platform_id
    total_requests: int
    total_tokens: int
    total_estimated_cost: Decimal

class LogSummaryResponse(BaseModel):
    start_date: date
    end_date: date
    group_by_field: str
    summary: List[LogSummaryItem]
